-- Estrutura inicial do banco de dados Sonder.
-- Este arquivo não contém contas nem avaliações de teste.
-- Execute em um banco vazio chamado sonder, conectado como sonder_user.

CREATE TABLE public.usuarios (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email character varying(100) NOT NULL,
    senha character varying(100) NOT NULL,
    nome character varying(100)
);

CREATE TABLE public.musicas (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo character varying(100) NOT NULL,
    artista character varying(100) NOT NULL,
    album character varying(100),
    nota numeric(2,1),
    comentario text,
    usuario_id integer REFERENCES public.usuarios(id)
);
